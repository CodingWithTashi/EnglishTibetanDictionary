package com.kharagedition.tibetandictionary.data.auth

import android.app.Activity
import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.kharagedition.tibetandictionary.R
import dagger.hilt.android.qualifiers.ApplicationContext
import javax.inject.Inject

/**
 * The "Sign in with Google" sheet through Credential Manager. `default_web_client_id` is generated by the
 * google-services plugin from the OAuth web client in `google-services.json`.
 */
class CredentialManagerGoogleSource @Inject constructor(
    @param:ApplicationContext private val context: Context,
) : GoogleCredentialSource {

    override suspend fun requestIdToken(activity: Activity): String? {
        val option = GetSignInWithGoogleOption.Builder(context.getString(R.string.default_web_client_id)).build()
        return try {
            val result = CredentialManager.create(activity)
                .getCredential(activity, GetCredentialRequest(listOf(option)))
            GoogleIdTokenCredential.createFrom(result.credential.data).idToken
        } catch (_: GetCredentialCancellationException) {
            null
        } catch (_: NoCredentialException) {
            // The button flow offers to add an account when there is none, so this is rare: treat it as a cancel.
            null
        }
    }

    override suspend fun clearCredentialState() {
        CredentialManager.create(context).clearCredentialState(ClearCredentialStateRequest())
    }
}
